"""Media-event placeholder helpers extracted from ``gateway/run.py``.

Part of the hermes-monolith-split refactor (Phase 1). Pure function; no
module-level state. The single import from ``gateway.platforms.base`` is
the ``MessageType`` enum that callers already pull through the gateway
package, so this stays clear of the cross-monolith import risk flagged
in plan v3 CDX-2.
"""

from gateway.platforms.base import MessageType


def _build_media_placeholder(event) -> str:
    """Build a text placeholder for media-only events so they aren't dropped.

    When a photo/document is queued during active processing and later
    dequeued, only .text is extracted.  If the event has no caption,
    the media would be silently lost.  This builds a placeholder that
    the vision enrichment pipeline will replace with a real description.
    """
    parts = []
    media_urls = getattr(event, "media_urls", None) or []
    media_types = getattr(event, "media_types", None) or []
    for i, url in enumerate(media_urls):
        mtype = media_types[i] if i < len(media_types) else ""
        if mtype.startswith("image/") or getattr(event, "message_type", None) == MessageType.PHOTO:
            parts.append(f"[User sent an image: {url}]")
        elif mtype.startswith("audio/"):
            parts.append(f"[User sent audio: {url}]")
        else:
            parts.append(f"[User sent a file: {url}]")
    return "\n".join(parts)
